"""
refresh_file_map.py — rebuilds the Obsidian graph hub notes for the
Receiving Task Automation vault.

Run after a receiving run (or any time files change):
    python "Project Map\\_scripts\\refresh_file_map.py"

What it does (and nothing else):
  * Cluster hubs: one "_Hub - <name>.md" per note folder (01-04), linking
    every note in that folder, so each colour clumps together in Graph view.
  * File hubs: "Project Map\\06 Files\\" notes linking every non-note file the
    automation work leaves in this folder (manifests, backups, scripts,
    validation documents, tool files), grouped by category.
Only writes inside "Project Map\\". Never touches receive.py, prf_helpers.py,
CLAUDE.md, logs, backups or any Box folder. Not part of the validated tool.
"""
import pathlib, re, datetime, urllib.parse

VAULT = pathlib.Path(__file__).resolve().parents[2]
PM = VAULT / "Project Map"
STAMP = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
HEADER = ("---\ntags: [hub, generated]\n---\n\n"
          "*Generated by `Project Map/_scripts/refresh_file_map.py` on {stamp}. "
          "Re-run the script instead of editing this note by hand.*\n\n")

SKIP_DIRS = {".obsidian", ".git", "__pycache__", "gs10.07.1", "Project Map"}
SKIP_PREFIXES = ("_backup/Project Map.pre-", "_backup/canvas-graph.pre-")

def link(rel):
    """Wikilink to a vault file; markdown link if the name has wikilink-breaking characters."""
    if re.search(r"[\[\]|#^]", rel):
        return f"[{pathlib.PurePosixPath(rel).name}]({urllib.parse.quote(rel)})"
    return f"[[{rel}]]"

def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    body_new = text.split("\n", 6)[-1]
    if old is not None and old.split("\n", 6)[-1] == body_new:
        return False                        # unchanged apart from the timestamp
    path.write_text(text, encoding="utf-8")
    return True

changed = []

# ---------- cluster hubs (notes) ----------
CLUSTERS = [
    ("01 Governance", "_Hub - Instruction (WI-7.4.3-01)",
     "The controlled instruction: CLAUDE.md and every governance / step page.", ["CLAUDE.md"]),
    ("02 Code", "_Hub - Code", "Notes documenting the automation code.", []),
    ("03 Validation", "_Hub - Validation", "QF 7.4.3-06 validation package notes.", []),
    ("04 History", "_Hub - History", "How the project got here.", []),
]
for folder, hub, blurb, extra in CLUSTERS:
    notes = sorted(p.stem for p in (PM / folder).glob("*.md") if not p.stem.startswith("_Hub"))
    lines = [HEADER.format(stamp=STAMP), f"# {hub[1:].strip(' -')}\n", f"{blurb} Part of [[00 Index]].\n"]
    lines += [f"- [[{e}]]" for e in extra] + [f"- [[{n}]]" for n in notes]
    if write(PM / folder / f"{hub}.md", "\n".join(lines) + "\n"):
        changed.append(hub)

# ---------- file hubs (attachments) ----------
files = []
for p in VAULT.rglob("*"):
    if not p.is_file():
        continue
    rel = p.relative_to(VAULT).as_posix()
    if rel.split("/")[0] in SKIP_DIRS or rel.startswith(SKIP_PREFIXES):
        continue
    if p.suffix.lower() == ".md" and rel != "CLAUDE.md":
        continue
    if rel == "CLAUDE.md":
        continue                            # lives in the Instruction hub
    files.append(rel)

def cat(rel):
    top = rel.split("/")[0]
    name = pathlib.PurePosixPath(rel).name
    if top == "logs":
        return "Run Manifests"
    if top == "_backup":
        return "Backups and Pre-Run Snapshots"
    if top == "Validation":
        return "Validation Documents"
    if "/" not in rel and re.match(r"(process|prefill)_.*\.py$|find_stadiums\.py$|inspect_annots\.py$", name):
        return "Edge-Case Scripts"
    return "Tool Files"

BLURB = {
    "Run Manifests": "One manifest per part per run, written by write_manifest() to `logs\\`. Development aid, not a quality record. See [[Step 9 - Run Manifest (Desktop Dev Aid)]].",
    "Backups and Pre-Run Snapshots": "Copies taken before edits or re-runs. Desktop copies only; the signed package in each PO's Completed Receiving is the record.",
    "Edge-Case Scripts": "Per-PO scripts outside the governed path. See [[Edge-Case Scripts]].",
    "Validation Documents": "Controlled QF 7.4.3-06 documents. See [[_Hub - Validation]].",
    "Tool Files": "The tool itself and its working files: receive.py, prf_helpers.py, templates, caches, installers.",
}
groups = {}
for rel in sorted(files):
    groups.setdefault(cat(rel), []).append(rel)

for name in BLURB:
    items = groups.get(name, [])
    lines = [HEADER.format(stamp=STAMP), f"# Files — {name}\n",
             f"{BLURB[name]} Part of [[_Hub - Files]]. **{len(items)} files.**\n"]
    if name == "Backups and Pre-Run Snapshots":
        sub = {}
        for rel in items:
            parts = rel.split("/")
            sub.setdefault(parts[1] if len(parts) > 2 else "(top level)", []).append(rel)
        for k in sorted(sub):
            lines.append(f"\n## {k}\n")
            lines += [f"- {link(r)}" for r in sub[k]]
    else:
        lines += [f"- {link(r)}" for r in items]
    if write(PM / "06 Files" / f"Files - {name}.md", "\n".join(lines) + "\n"):
        changed.append(name)

master = [HEADER.format(stamp=STAMP), "# Files produced and used by the automation\n",
          "Everything non-note in this folder, grouped. Part of [[00 Index]]. "
          "Ghostscript (`gs10.07.1`), `__pycache__` and the backup copies of vault notes are left out on purpose.\n"]
master += [f"- [[Files - {n}]] ({len(groups.get(n, []))})" for n in BLURB]
if write(PM / "06 Files" / "_Hub - Files.md", "\n".join(master) + "\n"):
    changed.append("Files hub")

print(f"{len(files)} files mapped across {len(groups)} categories; "
      f"{len(changed)} hub(s) updated: {', '.join(changed) or 'none'}")
